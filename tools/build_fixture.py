def build_corpus() -> dict[str, Any]:
    """生成完整语料（纯数据，不落盘）。

    Returns:
        与 ``fixture_corpus.json`` 结构一致、可直接 ``json.dump`` 的字典。
    """
    notes: list[dict[str, Any]] = []
    comments: list[dict[str, Any]] = []
    note_no = 0
    comment_no = 0

    for topic_no, topic in enumerate(_TOPICS):
        name: str = topic["name"]
        trend: str = topic["trend"]
        used: set[str] = set()

        for index in range(topic["notes"]):
            note_no += 1
            note_id = f"6a1b2c3d{note_no:04d}"
            ctx = _context(topic_no, index)
            publish_time = _publish_time(note_id, trend)

            title = _fill(topic["titles"][index], ctx)
            used.add(title)
            descs = topic["descs"]

            def pick_desc(bump: int) -> str:
                return _fill(descs[(index + bump) % len(descs)], ctx)

            desc = _unique(pick_desc, used)

            # 评论条数 3-8：上限与下限都取到，避免所有笔记都是同一个长度
            comment_count = 3 + int(_u(note_id, "comment-count") * 6)
            noise_slot = int(_u(note_id, "noise-slot") * comment_count)
            with_noise = _u(note_id, "noise") < 0.83

            image_count = 1 + int(_u(note_id, "images") * 4)
            likes = _note_likes(note_id)
            notes.append(
                {
                    "note_id": note_id,
                    "title": title,
                    "desc": desc,
                    "url": f"https://www.example.invalid/explore/{note_id}",
                    "images": [f"synthetic://{note_id}/{i}" for i in range(image_count)],
                    "likes": likes,
                    "collects": int(likes * (0.3 + 0.6 * _u(note_id, "collects"))),
                    "comments_count": comment_count + int(_u(note_id, "cc-bump") * 300),
                    "publish_time": publish_time.isoformat(),
                    "author_hash": hash_id(note_id, salt="fixture-author"),
                    "truth_label": name,
                }
            )

            note_comment_ids: list[str] = []
            for j in range(comment_count):
                comment_no += 1
                comment_id = f"c{comment_no:05d}"
                note_comment_ids.append(comment_id)

                if with_noise and j == noise_slot:
                    text = _NOISE[int(_u(comment_id, "noise") * len(_NOISE))]
                    label = ""
                else:

                    def pick(bump: int) -> str:
                        return _comment_text(topic, ctx, note_id, j, bump)

                    text = _unique(pick, used)
                    label = name

                created = publish_time + timedelta(hours=1 + int(_u(comment_id, "at") * 72))
                comments.append(
                    {
                        "comment_id": comment_id,
                        "note_id": note_id,
                        "content": text,
                        "likes": _comment_likes(comment_id),
                        # 二级评论是「评论区的评论区」这类深层痛点的来源，
                        # 语料里必须真的存在，否则下游没有可用的回复语境
                        "parent_id": note_comment_ids[0]
                        if j > 0 and _u(comment_id, "parent") < 0.16
                        else None,
                        "created_at": min(created, ANCHOR).isoformat(),
                        "user_hash": hash_id(comment_id, salt="fixture-user"),
                        "truth_label": label,
                    }
                )

    return {
        "_meta": {
            "purpose": "内置脱敏样例语料，供 CI、Demo 与离线验证使用。",
            "notice": (
                "本文件由 tools/build_fixture.py 确定性生成，请勿手工编辑。"
                "内容为虚构数据，不来自任何真实平台采集：笔记 URL 落在 .invalid 保留顶级域，"
                "图片地址使用 synthetic:// 合成图协议（见 synthetic.py），两者都不会被真实请求。"
            ),
            "generated_by": "tools/build_fixture.py",
            "anchor_date": ANCHOR.date().isoformat(),
            "expected_clusters": [topic["name"] for topic in _TOPICS],
        },
        "keyword": KEYWORD,
        "notes": notes,
        "comments": comments,
    }


def _verify(corpus: dict[str, Any]) -> None:
    """生成后自检 —— 语料一旦违反契约就立刻报错，而不是写出一个"看起来正常"的文件。

    这里检查的都是**不会让任何下游报错、只会让结果静默失真**的性质：
    标签错位、噪声没被过滤、主题文本被误杀、发布时间跑到未来。
    """
    labels = set(corpus["_meta"]["expected_clusters"])
    seen: set[str] = set()
    noise_count = 0
    counts: dict[str, int] = {}

    for note in corpus["notes"]:
        assert note["truth_label"] in labels, f"笔记标签越界: {note['note_id']}"
        counts[note["truth_label"]] = counts.get(note["truth_label"], 0) + 1
        for i, url in enumerate(note["images"]):
            assert url == f"synthetic://{note['note_id']}/{i}", f"图片地址不合规: {url}"
        assert "{" not in note["title"] and "{" not in note["desc"], "槽位未被填充"
        note_text = note["title"] + " " + note["desc"]
        assert not is_noise(note_text), f"主题笔记被误判为噪声: {note['title']}"
        assert datetime.fromisoformat(note["publish_time"]) <= ANCHOR, "发布时间不该在未来"

    for comment in corpus["comments"]:
        text = comment["content"]
        if comment["truth_label"] == "":
            noise_count += 1
            # 验收门③要求噪声被过滤掉；拦不住的噪声必须在这里暴露，而不是等到聚类
            assert is_noise(text), f"噪声未被 is_noise 拦截: {text!r}"
        else:
            assert comment["truth_label"] in labels, f"评论标签越界: {comment['comment_id']}"
            assert not is_noise(text), f"主题评论被误判为噪声: {text!r}"
        assert text not in seen or comment["truth_label"] == "", f"主题文本重复: {text!r}"
        if comment["truth_label"]:
            seen.add(text)

    for topic in corpus["_meta"]["expected_clusters"]:
        assert 18 <= counts.get(topic, 0) <= 22, f"{topic} 的笔记数越界: {counts.get(topic, 0)}"

    total = len(corpus["comments"])
    ratio = noise_count / total
    assert 0.10 <= ratio <= 0.20, f"噪声比例越界: {ratio:.3f}"
    assert total >= 800, f"评论数不足: {total}"


def main(argv: list[str] | None = None) -> int:
    """命令行入口：重新生成并写回语料文件。"""
    parser = argparse.ArgumentParser(description="生成内置样例语料 fixture_corpus.json")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="输出路径")
    args = parser.parse_args(argv)

    corpus = build_corpus()
    _verify(corpus)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        json.dumps(corpus, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    notes = len(corpus["notes"])
    comments = len(corpus["comments"])
    noise = sum(1 for c in corpus["comments"] if not c["truth_label"])
    print(
        f"已写出 {args.out}\n"
        f"  笔记 {notes} 篇 / 评论 {comments} 条 / 噪声 {noise} 条 "
        f"({noise / comments:.1%})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
