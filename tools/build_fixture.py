_SLOT = re.compile(r"\{(\w+)\}")


# --------------------------------------------------------------------------- #
# 确定性取值
# --------------------------------------------------------------------------- #


def _u(*parts: str) -> float:
    """由字符串派生一个 ``[0, 1)`` 的确定性伪随机数。

    用哈希而不是 ``random``：脚本必须可重复运行，且同一份语料在任何机器上
    生成出的字节都要一致 —— 否则提交的 JSON 与脚本产出对不上，守卫测试就废了。
    """
    return int(hash_id("\x1f".join(parts), salt="fixture-v1"), 16) / float(16**16)


def _fill(template: str, ctx: dict[str, str]) -> str:
    """填充 ``{槽位}`` 模板。没有对应槽位的占位符原样保留。"""
    return _SLOT.sub(lambda match: ctx.get(match.group(1), match.group(0)), template)


def _context(topic_no: int, index: int) -> dict[str, str]:
    """给一篇笔记生成一组槽位取值。

    四个槽位用互质的步长错开，保证相邻笔记的组合不重样 —— 只错开一个槽位
    会让 22 篇笔记里出现大量"只差一个词"的近似重复。
    """
    return {
        "肤质": _SKIN[(index * 3 + topic_no) % len(_SKIN)],
        "场景": _SCENE[(index * 5 + topic_no * 2) % len(_SCENE)],
        "时间": _TIME[(index * 7 + topic_no) % len(_TIME)],
        "产品": _PRODUCT[(index * 11 + topic_no * 3) % len(_PRODUCT)],
    }


def _unique(pick: Callable[[int], str], used: set[str]) -> str:
    """按确定性顺序取一条本主题尚未用过的文本。

    撞车时靠 ``bump`` 换一组槽位重试，而不是放宽重复 —— 同一主题里出现两条
    一模一样的文本会让聚类质量虚高（同一条证据被算成两次）。
    """
    candidate = pick(0)
    for bump in range(1, 32):
        if candidate not in used:
            break
        candidate = pick(bump)
    used.add(candidate)
    return candidate


def _publish_time(note_id: str, trend: str) -> datetime:
    """按主题趋势生成发布时间。

    趋势必须真的体现在时间分布上：``cluster_quality`` 的 stage 判定靠它，
    如果所有主题都均匀铺开，"增长趋势"这个因子就永远测不出差异。
    """
    u = _u(note_id, "publish")
    if trend == "rising":
        days = 6 + int(160 * u**1.8)
    elif trend == "declining":
        days = 200 + int(350 * u**0.5)
    else:
        days = 6 + int(544 * u)
    hours = int(_u(note_id, "publish-h") * 14)
    minutes = int(_u(note_id, "publish-m") * 60)
    return ANCHOR - timedelta(days=days, hours=hours, minutes=minutes)


# 评论的句式。纯主句只占十分之一：它没有任何可变的修饰成分，同一主题里最多只能
# 产出 16 种（主句池大小），放太多必然撞车；其余句式都带上句首或后半句，
# 组合空间立刻升到百量级，同一主题内不会出现重样的句子。
_SHAPES = (
    "core",
    "opening+core",
    "core+tail",
    "opening+core+tail",
    "opening+core",
    "core+tail",
    "opening+core+tail",
    "core+tail",
    "opening+core",
    "core+tail",
)


def _comment_text(
    topic: dict[str, Any], ctx: dict[str, str], note_id: str, j: int, bump: int
) -> str:
    """组合出一条评论。

    openings / cores / tails 三段各自独立取值，组合空间（10 × 16 × 18 = 2880）
    远大于单个主题 90 条评论的量，因此同一主题内几乎不会出现重样的句子。
    只换句首或只换主句会让语料退化成"同一句话改几个字"，那样测不出聚类能力。
    """
    base = int(_u(note_id, "base") * 9973)
    cores = topic["cores"]
    tails = (*topic["tails"], *_GENERIC_TAILS)

    core = cores[(base + (j + bump) * 3) % len(cores)]
    opening = _OPENINGS[(base + (j + bump) * 5) % len(_OPENINGS)]
    tail = tails[(base + (j + bump) * 7) % len(tails)]

    shape = _SHAPES[(j + base) % len(_SHAPES)]
    if shape == "core":
        raw = core
    elif shape == "opening+core":
        raw = opening + core
    elif shape == "core+tail":
        raw = core + tail
    else:
        raw = opening + core + tail
    return _fill(raw, ctx)


def _note_likes(note_id: str) -> int:
    """笔记点赞数。

    指数 2.2 让分布明显右偏：多数笔记点赞不高、少数爆款几千赞。均匀分布会让
    「点赞数有区分度」这条要求形同虚设 —— log 压缩后的权重全都挤在一起。
    """
    return int(_u(note_id, "likes") ** 2.2 * 9000)


def _comment_likes(comment_id: str) -> int:
    """评论点赞数，同样右偏，量级比笔记小一个数量级。"""
    return int(_u(comment_id, "likes") ** 2.0 * 1600)


